"""Regenerates gui/qml/Puzzles.js, the Bitcoin puzzle list of the desktop app, from the blockchain.

  python gui/puzzles.py

The addresses come from the puzzle transaction itself (2015-01-15), whose output n-1 pays puzzle n;
the mapping is checked against the known keys of solved puzzles. Balances and spends come from the
Blockstream Esplora API (about 160 requests, a minute or two).
"""
import datetime, json, os, sys, time, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'bench'))
from bench import addr_from_key  # noqa: E402

TXID = '08389f34c98c606322740c0be6a7125d9860bb8d5cb182c02f98461e5fa6cd15'
API = 'https://blockstream.info/api'
KNOWN_KEYS = {1: 0x1, 2: 0x3, 3: 0x7, 4: 0x8, 5: 0x15, 6: 0x31, 7: 0x4C, 8: 0xE0, 9: 0x1D3, 10: 0x202,
              30: 0x3D94CD64}


def get(path):
    for attempt in range(5):
        try:
            with urllib.request.urlopen(API + path, timeout=30) as r:
                return json.load(r)
        except Exception as e:          # rate limit or network hiccup: back off and retry
            print(f'  retry {path}: {e}', flush=True)
            time.sleep(3 * (attempt + 1))
    sys.exit(f'no answer for {path}')


def main():
    addrs = [v['scriptpubkey_address'] for v in get(f'/tx/{TXID}')['vout'][:160]]
    for n, k in KNOWN_KEYS.items():
        if addrs[n - 1] != addr_from_key(k):
            sys.exit(f'output {n - 1} is not puzzle #{n}: the transaction layout is not what this script expects')

    rows = []
    for n, a in enumerate(addrs, 1):
        d = get(f'/address/{a}')
        c, m = d['chain_stats'], d['mempool_stats']
        balance = (c['funded_txo_sum'] + m['funded_txo_sum'] - c['spent_txo_sum'] - m['spent_txo_sum']) / 1e8
        spends = c['spent_txo_count'] + m['spent_txo_count']
        # Any spend reveals the public key; with money left the puzzle is still open
        rows.append(f'    {{ n: {n}, address: "{a}", balance: {balance:.8f}, solved: {str(balance == 0).lower()}, '
                    f'pubkey: {str(spends > 0).lower()} }}')
        if n % 20 == 0:
            print(f'  {n}/160', flush=True)
        time.sleep(0.25)

    today = datetime.date.today().isoformat()
    out = os.path.join(ROOT, 'gui', 'qml', 'Puzzles.js')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('.pragma library\n'
                '// SPDX-License-Identifier: AGPL-3.0-only\n'
                '// Generated by gui/puzzles.py, do not edit. Bitcoin puzzle n keeps its key in [2^(n-1), 2^n - 1].\n'
                f'// Addresses: outputs of transaction {TXID}.\n'
                f'// balance (BTC), solved (nothing left) and pubkey (public key on the chain) as of {today}.\n\n'
                f'var asOf = "{today}"\n\n'
                'var list = [\n' + ',\n'.join(rows) + '\n]\n')
    print('wrote', out)


if __name__ == '__main__':
    main()
